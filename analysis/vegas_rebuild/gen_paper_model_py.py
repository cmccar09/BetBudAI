def model_ln_probs(score_breakdowns, segment='full'):
    """score_breakdowns: list of dict (one per runner in a race, any subset
    of FEATURES; missing keys treated as 0). Returns a list of raw (linear)
    scores s_i = w . standardized(x_i) — NOT yet softmaxed — one per runner,
    same order as input. Caller applies softmax (see vegas_paper.py)."""
    m = AW if segment == 'aw' else FULL
    w = m['weights']
    mean = m['feature_mean']
    std = m['feature_std']
    out = []
    for bd in score_breakdowns:
        s = 0.0
        for i, feat in enumerate(FEATURES):
            v = float(bd.get(feat, 0) or 0)
            z = (v - mean[i]) / (std[i] if std[i] else 1.0)
            s += w[i] * z
        out.append(s)
    return out
